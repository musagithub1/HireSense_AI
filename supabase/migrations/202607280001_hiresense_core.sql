create or replace function public.start_practice_interview(
  p_interview_id uuid,
  p_company_key text,
  p_company_name text,
  p_job_title text,
  p_job_description text,
  p_resume_text text,
  p_language_key text,
  p_language_code text,
  p_interview_type text,
  p_mode text,
  p_model text,
  p_total_questions integer
)
returns table (interview_id uuid, application_id uuid, job_id uuid)
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
  v_job_id uuid;
  v_application_id uuid;
begin
  if v_user_id is null then
    raise exception 'Authentication is required';
  end if;
  if p_interview_id is null then
    raise exception 'Interview id is required';
  end if;

  insert into public.jobs (
    owner_id,
    company_key,
    company_name,
    title,
    description,
    status
  )
  values (
    v_user_id,
    left(coalesce(p_company_key, 'general'), 80),
    left(coalesce(p_company_name, ''), 160),
    left(coalesce(nullif(p_job_title, ''), 'Practice role'), 160),
    left(coalesce(p_job_description, ''), 60000),
    'practice'
  )
  returning id into v_job_id;

  insert into public.applications (
    job_id,
    candidate_id,
    resume_text,
    status,
    consented_at
  )
  values (
    v_job_id,
    v_user_id,
    left(coalesce(p_resume_text, ''), 60000),
    'practice',
    now()
  )
  returning id into v_application_id;

  insert into public.interviews (
    id,
    application_id,
    owner_id,
    interview_type,
    company_key,
    language_key,
    language_code,
    mode,
    status,
    model,
    total_questions,
    progress
  )
  values (
    p_interview_id,
    v_application_id,
    v_user_id,
    left(coalesce(p_interview_type, 'Mixed'), 50),
    left(coalesce(p_company_key, 'general'), 80),
    left(coalesce(p_language_key, 'en'), 20),
    left(coalesce(p_language_code, 'en-US'), 20),
    case when p_mode = 'live_voice' then 'live_voice' else 'text' end,
    'in_progress',
    left(coalesce(p_model, ''), 160),
    greatest(1, least(coalesce(p_total_questions, 5), 50)),
    jsonb_build_object(
      'current_question_num', 1,
      'awaiting_question', true,
      'awaiting_followup', false
    )
  );

  insert into public.audit_events (
    actor_id,
    event_type,
    entity_type,
    entity_id
  )
  values (
    v_user_id,
    'interview_started',
    'interview',
    p_interview_id
  );

  return query select p_interview_id, v_application_id, v_job_id;
end;
$$;

