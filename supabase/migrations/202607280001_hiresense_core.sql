create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  full_name text not null default '',
  role text not null default 'candidate'
    check (role in ('candidate', 'recruiter', 'admin')),
  locale text not null default 'en',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.jobs (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references auth.users(id) on delete cascade,
  company_key text not null default 'general',
  company_name text not null default '',
  title text not null,
  description text not null,
  required_skills jsonb not null default '[]'::jsonb,
  status text not null default 'practice'
    check (status in ('draft', 'open', 'closed', 'practice')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.applications (
  id uuid primary key default gen_random_uuid(),
  job_id uuid not null references public.jobs(id) on delete cascade,
  candidate_id uuid not null references auth.users(id) on delete cascade,
  resume_text text not null default '',
  resume_path text,
  consented_at timestamptz not null default now(),
  status text not null default 'practice'
    check (status in ('draft', 'submitted', 'interview', 'completed', 'practice')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.interviews (
  id uuid primary key,
  application_id uuid not null references public.applications(id) on delete cascade,
  owner_id uuid not null references auth.users(id) on delete cascade,
  interview_type text not null default 'Mixed',
  company_key text not null default 'general',
  language_key text not null default 'en',
  language_code text not null default 'en-US',
  mode text not null default 'text'
    check (mode in ('text', 'live_voice')),
  status text not null default 'in_progress'
    check (status in ('in_progress', 'completed', 'abandoned')),
  model text not null default '',
  total_questions integer not null default 5
    check (total_questions between 1 and 50),
  progress jsonb not null default '{}'::jsonb,
  metrics jsonb not null default '{}'::jsonb,
  report_markdown text not null default '',
  evidence_assessment jsonb,
  started_at timestamptz not null default now(),
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.interview_turns (
  id uuid primary key default gen_random_uuid(),
  interview_id uuid not null references public.interviews(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  turn_index integer not null check (turn_index > 0),
  question_number integer not null check (question_number > 0),
  is_followup boolean not null default false,
  question_original text not null,
  transcript_original text not null,
  transcript_confirmed boolean not null default false,
  language_key text not null default 'en',
  language_code text not null default 'en-US',
  english_translation text,
  transcription_engine text not null default 'typed',
  question_source text not null default 'model',
  speech_stats jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (interview_id, turn_index)
);

create table if not exists public.evaluation_scores (
  id uuid primary key default gen_random_uuid(),
  interview_id uuid not null references public.interviews(id) on delete cascade,
  owner_id uuid not null references auth.users(id) on delete cascade,
  dimension text not null,
  score numeric(2,1) check (score is null or score between 1 and 5),
  evidence_excerpt text,
  evidence jsonb not null default '[]'::jsonb,
  reason text not null default '',
  reliability text not null default 'Unavailable',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (interview_id, dimension)
);

create table if not exists public.audit_events (
  id bigint generated by default as identity primary key,
  actor_id uuid references auth.users(id) on delete set null,
  event_type text not null,
  entity_type text not null,
  entity_id uuid,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

